import { createReadStream } from 'node:fs'
import { mkdir, open, realpath, rm } from 'node:fs/promises'
import { dirname, resolve, sep } from 'node:path'
import { InvalidStorageKeyError, isValidStorageKey, StorageObjectExistsError, StorageObjectNotFoundError, type StorageDriver } from './storageDriver'

// The contract moved to ./storageDriver (shared with the S3 driver); re-exported for existing importers.
export { InvalidStorageKeyError, isValidStorageKey, StorageObjectExistsError, StorageObjectNotFoundError, type StorageDriver } from './storageDriver'

function isMissing(error: unknown): boolean {
  const code = (error as { code?: unknown } | null)?.code
  return code === 'ENOENT' || code === 'ENOTDIR'
}

export class LocalStorageDriver implements StorageDriver {
  private readonly root: string

  constructor(rootDir: string) {
    this.root = resolve(rootDir)
  }

  /**
   * Keys are generated by the server (`<orgId>/<yyyy>/<uuid>.<ext>`); this still refuses anything
   * else: traversal, absolute paths, separators other than `/`, empty segments, NUL, spaces. The
   * resolved path must also stay strictly below the root (belt and braces over the key grammar).
   */
  private pathFor(key: string): string {
    if (!isValidStorageKey(key)) throw new InvalidStorageKeyError(key)
    const full = resolve(this.root, key)
    if (!full.startsWith(this.root + sep)) throw new InvalidStorageKeyError(key)
    return full
  }

  /** `real` (a realpath) must lie strictly below the root's own realpath — a symlink inside the tree cannot lead out of it. */
  private assertBelowRoot(realRoot: string, real: string, key: string): void {
    if (!real.startsWith(realRoot + sep)) throw new InvalidStorageKeyError(key)
  }

  /** The existing object's real path, or null when it does not exist. Throws for a symlink escaping the root. */
  private async existingPath(key: string): Promise<string | null> {
    const full = this.pathFor(key)
    let realRoot: string
    let real: string
    try {
      realRoot = await realpath(this.root)
      real = await realpath(full)
    }
    catch (error) {
      if (isMissing(error)) return null
      throw error
    }
    this.assertBelowRoot(realRoot, real, key)
    return real
  }

  async put(key: string, bytes: Uint8Array) {
    const path = this.pathFor(key)
    await mkdir(dirname(path), { recursive: true })
    // A symlinked directory inside the root must not redirect the write outside it.
    this.assertBelowRoot(await realpath(this.root), await realpath(dirname(path)), key)
    // 'wx' = O_CREAT | O_EXCL: fails with EEXIST if anything (a file, or a symlink — even a dangling one) is there.
    const handle = await open(path, 'wx').catch((error: unknown) => {
      throw (error as { code?: unknown } | null)?.code === 'EEXIST' ? new StorageObjectExistsError() : error
    })
    try {
      await handle.writeFile(bytes)
    }
    catch (error) {
      // The object was created by this call and is incomplete: remove it so no partial file remains.
      await handle.close().catch(() => undefined)
      await rm(path, { force: true }).catch(() => undefined)
      throw error
    }
    await handle.close()
  }

  async get(key: string) {
    const path = await this.existingPath(key)
    if (path === null) throw new StorageObjectNotFoundError()
    return createReadStream(path)
  }

  async exists(key: string) {
    return (await this.existingPath(key)) !== null
  }

  async delete(key: string) {
    const path = await this.existingPath(key)
    if (path !== null) await rm(path, { force: true })
  }
}
